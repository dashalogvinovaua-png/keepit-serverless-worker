# Скачка WAN 2.2 ANIMATE на сетевой том RunPod (запускать на поде с примонтированным томом).
#
# ЗАЧЕМ ЭТА МОДЕЛЬ ФЕРМЕ. Копии трендов делают три движка, и по лицу блогера годится один — чужой
# и дорогой (fal Wan 2.7, $1.70 за начатые 10 секунд). Свои два не годятся каждый по своей причине,
# и обе причины — устройство, а не настройка:
#   • Wan 2.2 VACE держит лицо на 35 из 100 (замер судьи 05.08): у него нет никакого механизма
#     личности, только слабый reference_image — оттого «на первой секунде рыжая, на пятнадцатой
#     блондинка»;
#   • SCAIL лицо держит хорошо, но рисует кадр ЗАНОВО (denoise 1.0) — обстановку, одежду и предметы
#     он сохранять не умеет и не собирался.
#
# Wan 2.2 Animate устроен под нашу задачу прямо: на вход идёт исходный ролик и кадр блогера, наружу
# выходит тот же ролик с блогером вместо героя — поза, мимика и губы переносятся, а отдельная
# relight-LoRA подгоняет свет и цвет под сцену, чтобы вставленный человек не выглядел наклейкой.
#
# ЛИЦЕНЗИЯ ПРОВЕРЕНА ПО КУСКАМ, а не по заголовку карточки — на ферме уже был случай, когда
# «Apache 2.0» у DiffRhythm оказался только на код, а обязательные части шли под запретом на
# коммерцию. Здесь: сами веса Wan2.2-Animate-14B — Apache 2.0; спутники (umt5, wan_2.1_vae,
# clip_vision_h) у нас УЖЕ в производстве под wan и scail, новых обязательств не появляется.
# Ускоряющая LoRA lightx2v — Apache 2.0. Ни одного research-only куска в наборе нет.
# (Для сравнения: ID-V2V от Eyeline/Netflix в ComfyUI заведён, но отдан «for demonstration and
# inspiration only» — его тут нет намеренно, и появиться он не должен.)
#
# ПОЧЕМУ НА ТОМ, А НЕ В ОБРАЗ: serverless-воркер эфемерный, кэш умирает вместе с контейнером.
# 20 ГБ на каждом холодном старте — разорение. На томе модель лежит один раз.
# Узел WanAnimateToVideo — В ЯДРЕ ComfyUI (наш образ собран на ядре не старше 11.08.2026),
# отдельный набор узлов ради самой модели ставить не нужно.
#
# Запуск на поде (GPU НЕ нужен — хватает дешёвого CPU-пода с примонтированным томом):
#   pip install -U "huggingface_hub[hf_transfer]"
#   python3 dl_animate_models.py
import os
import shutil

# Xet-транспорт HuggingFace рвётся на сетевом томе RunPod («Internal Writer Error») и оставляет
# модель НЕДОКАЧАННОЙ — на этом уже сломался шардированный HeartMuLa. Выключаем до импорта.
os.environ.setdefault('HF_HUB_DISABLE_XET', '1')

from huggingface_hub import hf_hub_download

M = os.environ.get('MODELS_DIR', '/workspace/comfyui/models')

# (репозиторий, путь в репозитории, папка ComfyUI, зачем)
FILES = [
    # ── САМА МОДЕЛЬ ──
    # Берём fp8_scaled от Kijai — ИМЕННО ЭТОТ файл назван в нативном руководстве ComfyUI, то есть
    # это проверенная другими дорога, а не наш выбор наугад. 18,4 ГБ против 34,6 у bf16: на наших
    # картах (RTX 6000 Ada / L40 / L40S — все 48 ГБ) bf16 влез бы, но оставил бы слишком мало
    # места под кадры на 720p. Грузится он как scail — UNETLoader с weight_dtype='default':
    # масштаб уже вшит в файл, второй раз квантовать нечего.
    ('Kijai/WanVideo_comfy_fp8_scaled',
     'Wan22Animate/Wan2_2-Animate-14B_fp8_e4m3fn_scaled_KJ.safetensors',
     'diffusion_models', 'сама модель: перенос позы, мимики и губ на блогера'),

    # ── RELIGHT-LoRA: свет и цвет сцены на вставленном человеке ──
    # Без неё блогер выглядит наклейкой из другого помещения: у SCAIL ровно это лечили такой же
    # LoRA. Берём официальную перепаковку Comfy-Org (bf16), а не сторонний ресайз.
    ('Comfy-Org/Wan_2.2_ComfyUI_Repackaged',
     'split_files/loras/wan2.2_animate_14B_relight_lora_bf16.safetensors',
     'loras', 'relight: свет и цвет сцены на вставленном человеке'),

    # ── УСКОРЯЮЩАЯ LoRA: 4 шага вместо 20 ──
    # ЭТО НЕ УКРАШЕНИЕ, А ЦЕНА. Шаги — прямой множитель времени на GPU, а время на GPU и есть наш
    # счёт ($0,0006 за секунду). Двадцать шагов против четырёх — это пятикратный счёт за ту же
    # копию. Ровно на этом обжёгся SCAIL: его граф собран под 40 шагов и cfg 5, дистилляционной
    # LoRA на томе не оказалось, и вместо неё шаги просто прижали до 14 — то есть получили
    # НЕДОШУМЛЁННЫЙ кадр (это и есть «плывут глаза и зубы»), не выиграв в природе движка.
    # Здесь так не будет: ускорение берётся моделью, а не отниманием шагов.
    # Имя файла — то же, что в нативном руководстве ComfyUI.
    ('Kijai/WanVideo_comfy',
     'Lightx2v/lightx2v_I2V_14B_480p_cfg_step_distill_rank64_bf16.safetensors',
     'loras', 'ускорение: 4 шага вместо 20 — это пятикратная разница в счёте, а не в красоте'),

    # ── ПОЗА И ЛИЦО: SDPose (в ЯДРЕ ComfyUI, сторонних узлов не надо) ──
    # Animate ведут поза и мимика героя оригинала, и раньше их брали только у DWPose из набора
    # `comfyui_controlnet_aux`. Этот набор из нашего образа ВЫКИНУТ — он ронял ComfyUI на старте,
    # воркер уходил в unhealthy и переставал брать задачи вообще. Возвращать его нельзя ещё и по
    # второй причине: сборка образа на RunPod падает на тридцати минутах, а наши укладываются в
    # 15–31, то есть запаса нет.
    # Ничего этого и не нужно: в ядре ComfyUI теперь есть свои узлы SDPoseKeypointExtractor,
    # SDPoseDrawKeypoints (скелет), SDPoseFaceBBoxes и CropByBBoxes (кадр лица 512×512), а рамку
    # человека даёт RTDETR_detect. То есть весь препроцессинг Animate собирается из ЯДРА, и образ
    # трогать не нужно вовсе — нужны только эти два файла на томе.
    ('Comfy-Org/SDPose', 'checkpoints/sdpose_wholebody_fp16.safetensors',
     'checkpoints', 'поза и мимика: 134 точки тела, лица и кистей (узлы SDPose из ядра)'),
    ('Comfy-Org/SDPose', 'diffusion_models/rt_detr_v4-x-hgnet_fp16.safetensors',
     'diffusion_models', 'детектор человека: даёт рамку, без неё поза считается неточно'),
]

# СПУТНИКИ НЕ КАЧАЕМ — они уже на томе под wan и scail: umt5_xxl_fp8_e4m3fn_scaled (text_encoders),
# wan_2.1_vae (vae), clip_vision_h (clip_vision). Скачать их заново значит потратить время и место
# на копии того, что лежит. Но ПРОВЕРИТЬ, что они на месте, обязаны: если их нет, граф Animate
# упадёт уже на GPU, то есть за деньги. Проверка бесплатная — это просто чтение диска.
СПУТНИКИ = [
    ('text_encoders/umt5_xxl_fp8_e4m3fn_scaled.safetensors', 'текстовый энкодер (общий с wan/scail)'),
    ('vae/wan_2.1_vae.safetensors', 'VAE (общий с wan/scail)'),
    ('clip_vision/clip_vision_h.safetensors', 'clip vision (общий со scail)'),
]

скачано = []
for repo, rel, sub, зачем in FILES:
    имя = os.path.basename(rel)
    dst_dir = os.path.join(M, sub)
    os.makedirs(dst_dir, exist_ok=True)
    dst = os.path.join(dst_dir, имя)
    # Порог «файл на месте» — 50 МБ, а не 100: самый мелкий из набора (детектор человека) весит
    # 124 МБ, и порог в 100 стоял бы вплотную к нему. Порог, впритык проходящий по живому файлу, —
    # это будущая ложная тревога от любой пересборки чужого репозитория.
    if os.path.exists(dst) and os.path.getsize(dst) > 50_000_000:
        print(f'уже есть: {sub}/{имя} ({round(os.path.getsize(dst)/1e9, 2)} ГБ)')
        скачано.append(dst)
        continue
    print(f'качаю: {sub}/{имя} — {зачем}', flush=True)
    p = hf_hub_download(repo_id=repo, filename=rel, local_dir='/tmp/animate_dl')
    shutil.move(p, dst)
    print(f'  ok {round(os.path.getsize(dst)/1e9, 2)} ГБ')
    скачано.append(dst)

# ── ЧЕСТНЫЙ ИТОГ, А НЕ БОДРОЕ «DONE» ─────────────────────────────────────────
# Скрипт, который печатает «готово» независимо от того, что вышло, — это прибор, врущий только в
# сторону «всё хорошо». Такой не ловится никогда. Поэтому итог считаем по диску и при нехватке
# выходим НЕНУЛЁВЫМ кодом: пусть падает здесь, на дешёвом CPU-поде, а не потом на GPU за деньги.
беда = []
for dst in скачано:
    if not os.path.exists(dst) or os.path.getsize(dst) < 50_000_000:
        беда.append(f'недокачан: {dst}')

print('\n── спутники (должны уже лежать от wan/scail) ──')
for rel, зачем in СПУТНИКИ:
    p = os.path.join(M, rel)
    if os.path.exists(p):
        print(f'  есть: {rel} ({round(os.path.getsize(p)/1e9, 2)} ГБ) — {зачем}')
    else:
        беда.append(f'НЕТ спутника {rel} ({зачем}) — граф Animate упадёт на GPU, то есть за деньги')

try:
    ст = shutil.disk_usage(M)
    print(f'\nместо на томе: занято {round((ст.total - ст.free)/1e9)} ГБ из {round(ст.total/1e9)} ГБ, '
          f'свободно {round(ст.free/1e9)} ГБ')
except Exception:
    pass

if беда:
    print('\n!! ANIMATE MODELS НЕ ГОТОВЫ:')
    for b in беда:
        print('   -', b)
    raise SystemExit(1)

print('\nANIMATE MODELS DONE — все файлы на месте')

# Скачка WAN-DANCER на сетевой том RunPod (запускать на поде с примонтированным томом).
#
# Зачем эта модель ферме. Слово владельца (10 августа): «мне надо чтобы танец был динамичным и
# движения были под динамичную музыку». Ни один наш движок этого не может: LTX и Wan получают на
# вход текст и картинку, звука они НЕ СЛЫШАТ — попасть в удар им нечем. Облачный OmniHuman слышит,
# но берёт 0,16 доллара за секунду, и владелец отклонила его словами «дорого».
#
# Wan-Dancer-14B (Tongyi Lab, Alibaba) устроен иначе: МУЗЫКА У НЕГО ОБЯЗАТЕЛЬНЫЙ ВХОД, он ею и
# управляется. Плюс на вход идёт фотография человека — то есть лицо блогера попадает в модель
# сразу, а не пришивается свапом после. Лицензия Apache 2.0 (проверено по карточке репозитория):
# коммерческая съёмка разрешена без оговорок — в отличие от истории с DiffRhythm, где «Apache»
# оказался только на код, а обязательные части шли под запретом на коммерцию.
#
# Почему на ТОМ, а не в образ: serverless-воркер эфемерный, кэш умирает вместе с контейнером.
# 36,7 ГБ на каждом холодном старте — это разорение. На томе модель лежит один раз.
#
# Запуск на поде (GPU не нужен — хватает дешёвого CPU-пода с примонтированным томом):
#   pip install -U "huggingface_hub[hf_transfer]"
#   python3 dl_dancer_models.py
import os
import shutil

# Xet-транспорт HuggingFace рвётся на сетевом томе RunPod («Internal Writer Error») и оставляет
# модель НЕДОКАЧАННОЙ — на этом уже сломался шардированный HeartMuLa. Выключаем до импорта.
os.environ.setdefault('HF_HUB_DISABLE_XET', '1')

from huggingface_hub import hf_hub_download

M = os.environ.get('MODELS_DIR', '/workspace/comfyui/models')
REPO = 'Comfy-Org/Wan-Dancer'

# Модель идёт ДВУМЯ частями и работает только вместе: общая держит рисунок танца целиком,
# уточняющая доводит мелкую моторику. Скачать одну — значит получить неработающий набор,
# поэтому обе перечислены здесь, а не «по вкусу».
FILES = [
    ('diffusion_models/wan2.2_dancer_14b_global_fp8_scaled.safetensors', 'diffusion_models',
     'общая: рисунок танца и координация тела'),
    ('diffusion_models/wan2.2_dancer_14b_local_fp8_scaled.safetensors', 'diffusion_models',
     'уточняющая: мелкая моторика, кисти и стопы'),
]

# ЧЕГО ЗДЕСЬ НАМЕРЕННО НЕТ. Текстовый энкодер (umt5), CLIP Vision, VAE и ускоряющая LoRA
# у фермы УЖЕ лежат на томе — их принесли Wan 2.2 и SCAIL. Качать второй раз 10+ ГБ ради
# тех же файлов — это выброшенные деньги и место на томе, которого у нас 150 ГБ на всё.
# Если проверка покажет, что какого-то из них нет, — он добавится сюда отдельной строкой,
# с именем, а не молчаливым «скачаем на всякий случай».


def место(путь):
    try:
        u = shutil.disk_usage(путь)
        return u.free / 1e9
    except Exception:
        return None


def main():
    свободно = место(M) or место('/workspace') or 0
    print(f'свободно на томе: {свободно:.1f} ГБ')
    # Нужно 36,7 ГБ + запас на распаковку и служебные файлы. Падать на середине скачки
    # хуже, чем не начинать: недокачанный шард выглядит как файл и ломает граф молча.
    if свободно and свободно < 45:
        print('!! на томе меньше 45 ГБ — качать нельзя, недокачанная модель ломает граф молча')
        raise SystemExit(2)
    # Имя файла в репозитории УЖЕ содержит папку `diffusion_models/`, поэтому целью скачки
    # служит корень моделей: библиотека сама разложит по подпапкам. Складывать «папку в папку»
    # — классическая ошибка, дающая models/diffusion_models/diffusion_models/…, где граф
    # модель не найдёт и скажет невнятное «file not found».
    os.makedirs(M, exist_ok=True)
    for имя, _подпапка, зачем in FILES:
        print(f'>> {имя} — {зачем}')
        p = hf_hub_download(repo_id=REPO, filename=имя, local_dir=M)
        print('   лёг в', p)
    print('готово: Wan-Dancer на томе')


if __name__ == '__main__':
    main()
